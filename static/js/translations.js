// Client-side translation applier
function applyLanguage(lang) {
  if (!KRISHI_TRANSLATIONS[lang]) lang = "en";
  localStorage.setItem("smart_krishi_lang", lang);
  document.documentElement.lang = lang;
  
  if (lang === "te") {
    document.body.classList.add("telugu-font");
  } else {
    document.body.classList.remove("telugu-font");
  }

  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (KRISHI_TRANSLATIONS[lang] && KRISHI_TRANSLATIONS[lang][key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = KRISHI_TRANSLATIONS[lang][key];
      } else {
        el.innerHTML = KRISHI_TRANSLATIONS[lang][key];
      }
    }
  });

  // Update active pill in UI
  document.querySelectorAll(".btn-lang").forEach(btn => {
    if (btn.getAttribute("data-lang") === lang) {
      btn.classList.add("active");
    } else {
      btn.classList.remove("active");
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("smart_krishi_lang") || document.documentElement.lang || "en";
  applyLanguage(savedLang);
});
